"""Generate docs/tables.md and docs/messages.md from the code, so the reference never drifts.

    python scripts/gen_docs.py          (tests/test_docs.py fails when the committed files are stale)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tradingbots.bots import _REGISTRY  # noqa: E402
from tradingbots.core.schemas import TABLES  # noqa: E402

HEADER = "<!-- generated by scripts/gen_docs.py - do not edit by hand -->\n\n"


def tables_md() -> str:
    out = [HEADER, "# Tables\n\n",
           "Every table is Parquet under `data/tables/<table>/` (partitioned tables use `<key>=<value>/` folders) and is "
           "readable with DuckDB or Polars. Use the dashboard's Tables page, or `bots tables list | show | export`. "
           "Each table has one owner bot; nothing else writes it.\n\n"]
    out.append("| Table | Owner | Partition | Writes | What it holds |\n|---|---|---|---|---|\n")
    for name, td in TABLES.items():
        out.append(f"| [`{name}`](#{name}) | {td.owner} | {td.partition or '-'} | {td.mode} | {td.description} |\n")
    for name, td in TABLES.items():
        out.append(f"\n## {name}\n\n{td.description}. Owner: **{td.owner}** bot")
        if td.partition:
            out.append(f"; partitioned by `{td.partition}`")
        out.append(f"; {td.mode} writes.\n\n| Column | Type | Meaning |\n|---|---|---|\n")
        for col, (dtype, desc) in td.columns.items():
            out.append(f"| `{col}` | {dtype} | {desc} |\n")
    return "".join(out)


def messages_md() -> str:
    src = (ROOT / "src" / "tradingbots" / "core" / "topics.py").read_text(encoding="utf-8")
    events, kv = [], []
    for m in re.finditer(r'^([A-Z_]+) = "([^"]+)"(?:\s*#\s*(.*))?$', src, re.M):
        const, value, note = m.group(1), m.group(2), (m.group(3) or "").strip()
        (kv if const.startswith("KV_") else events).append((const, value, note))
    out = [HEADER, "# Messages\n\n",
           "Bots talk only through the bus: **events** (publish/subscribe, at-least-once; every subscribing bot gets "
           "every message), **commands** (`cmd.<bot>.<action>`, request/reply with a timeout) and a small "
           "**key-value store** for the latest state. Backends: SQLite (default), Redis, or in-memory for tests.\n\n",
           "## Events\n\n| Topic | Constant | Payload |\n|---|---|---|\n"]
    for const, value, note in events:
        out.append(f"| `{value}` | `{const}` | {note} |\n")
    out.append("\n## Key-value store\n\n| Key | Constant | Holds |\n|---|---|---|\n")
    for const, value, note in kv:
        out.append(f"| `{value}` | `{const}` | {note} |\n")
    out.append("| `hb:<bot>` | `kv_heartbeat(bot)` | each bot's heartbeat: status, counters, last error, details |\n")
    out.append("| `supervisor:status` | `supervisor.KV_SUPERVISOR` | every process the supervisor runs |\n")
    out.append("\n## Commands\n\nSend with `bus.request(\"cmd.<bot>.<action>\", data)`; the reply always has `ok`. "
               "Every bot also answers `shutdown`.\n\n| Bot | Commands |\n|---|---|\n")
    for bot, target in list(_REGISTRY.items()) + [("supervisor", "tradingbots.supervisor:SupervisorBot")]:
        mod = target.split(":")[0].replace(".", "/")
        text = (ROOT / "src" / f"{mod}.py").read_text(encoding="utf-8")
        cmds = sorted(set(re.findall(r'self\.command\("([a-z_]+)"', text)))
        out.append(f"| {bot} | {', '.join(f'`{c}`' for c in cmds) or '-'} |\n")
    return "".join(out)


def main() -> None:
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "tables.md").write_text(tables_md(), encoding="utf-8")
    (docs / "messages.md").write_text(messages_md(), encoding="utf-8")
    print("wrote docs/tables.md and docs/messages.md")


if __name__ == "__main__":
    main()
